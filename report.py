"""Generate a four-page technical report using actual experiment results."""
import json
import textwrap
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages


def build_report(output=Path('artifacts')):
    output = Path(output)
    r = json.loads((output/'results.json').read_text())
    config = r['configs'][str(r['selection']['alpha'])]['parameters']
    def page(pdf, title, sections, image=None, parameter_table=None):
        fig = plt.figure(figsize=(8.27, 11.69))
        fig.text(.09, .95, title, fontsize=17, weight='bold', va='top')
        y = .89
        for heading, body in sections:
            fig.text(.09, y, heading, fontsize=12, weight='bold', va='top')
            y -= .033
            lines = []
            for paragraph in body.split('\n'):
                lines.extend(textwrap.wrap(paragraph, 91) or [''])
            fig.text(.09, y, '\n'.join(lines), fontsize=10, va='top', linespacing=1.5)
            y -= len(lines)*.018 + .03
        if parameter_table:
            ax = fig.add_axes((.09, .53, .82, .30))
            ax.axis('off')
            table = ax.table(cellText=parameter_table, colLabels=['Hyperparameter', 'Final value'],
                             loc='center', cellLoc='left', colLoc='left')
            table.auto_set_font_size(False)
            table.set_fontsize(10)
            table.scale(1, 1.6)
        if image:
            ax = fig.add_axes((.07, .065, .86, .235))
            ax.imshow(plt.imread(image))
            ax.axis('off')
        fig.text(.09, .035, 'Topics in AI | Assignment I | COMSATS University, Attock', fontsize=8, color='gray')
        pdf.savefig(fig)
        plt.close(fig)
    with PdfPages(output/'technical_report.pdf') as pdf:
        page(pdf, 'Custom Q-Learning Agent for Taxi-v3', [
            ('1. Problem description',
             'The task is to navigate a taxi through a 5 x 5 grid, collect a passenger, and deliver them to a designated destination. Internal walls constrain movement. Taxi-v3 is created with gymnasium.make(), using Gymnasium 1.2.1 and its default deterministic dynamics.\n'
             'State encoding: ((row * 5 + column) * 5 + passenger) * 4 + destination. There are 500 encoded states: 25 taxi positions, five passenger positions (four landmarks or inside the taxi), and four destinations. Only a subset is reachable. The reset distribution has 300 valid starting states.\n'
             'Six actions: south, north, east, west, pickup, and dropoff. Rewards are -1 for an ordinary step, -10 for an illegal pickup/dropoff, and +20 for successful delivery. Delivery terminates the episode; the wrapper truncates it at 200 steps.'),
            ('2. Objective and scope',
             'Maximize expected discounted return while learning a short, reliable delivery policy. No pretrained policy, RL framework, action masking, planning model, or hand-coded route is used. NumPy stores the learned action values; Gymnasium supplies only the environment.\n'
             'The assignment requires source code, an executed notebook, saved model, rendered demonstration, convergence analysis, and hyperparameter sensitivity. All artifacts are generated by reproducible scripts in the repository.')])
        page(pdf, 'Methodology and implementation', [
            ('3. Q-learning update',
             'Q(s,a) <- Q(s,a) + alpha * [r + gamma * (1 - terminal) * max_b Q(s_next,b) - Q(s,a)].\n'
             'This off-policy temporal-difference rule moves the current estimate toward the observed reward plus the best estimated future value. The Q-table starts at zero. Terminal delivery has target r only. Time-limit truncation ends the rollout but retains the bootstrap because it is an external limit, not a terminal MDP state.'),
            ('4. Exploration and architecture',
             'At episode e (zero-based), epsilon = max(0.01, 1.0 * 0.999^e). With probability epsilon the agent samples uniformly from all six actions; otherwise it selects a maximal Q-value, breaking ties randomly during training. Evaluation uses deterministic argmax and epsilon zero.\n'
             'agent.py owns the table, action selection, Bellman update, and model persistence. utils.py implements training, independent evaluation, plotting, and RGB rendering. main.py orchestrates experiments and writes raw CSV logs and JSON metrics. report.py and build_notebook.py generate the remaining deliverables.'),
            ('5. Reproducibility and model selection',
             'Training seeds are 0, 1, and 2. Each learning-rate setting uses identical episode budgets and schedules. At 1,000-episode intervals, greedy policies are assessed on reset seeds 20000-20099. The learning rate is selected by final validation return averaged across training seeds; a tie selects the lower rate. Deployment always uses training seed 0.\n'
             'After selection, every policy and a uniform-random baseline are evaluated on 500 separate reset seeds 30000-30499. The GIF uses another reset seed (40000). Validation rollouts do not update the Q-table or consume the training RNG. The test set does not select hyperparameters.')])
        table = []
        for alpha in ('0.1','0.5','0.9'):
            vals = r['test'][alpha]
            ret = [v['mean_return'] for v in vals]
            success = [v['success_rate']*100 for v in vals]
            table.append(f'alpha={alpha}: return {np.mean(ret):.3f} +/- {np.std(ret):.3f}; success {np.mean(success):.2f}%; steps {np.mean([v["mean_steps"] for v in vals]):.2f}')
        page(pdf, 'Experimental setup and measured results', [
            ('6. Final hyperparameters', 'All settings except alpha are held fixed. The sensitivity sweep is alpha in {0.1, 0.5, 0.9}.' + '\n'*18),
            ('7. Held-out performance', '\n'.join(table) + '\nValues are mean +/- population SD of three seed-level mean returns; these are descriptive spreads, not confidence intervals. The chart shows smoothed training returns and independent greedy validation success.')], output/'learning_curves.png',
             [[k, str(v)] for k,v in config.items()] + [['Q-table', '500 x 6 float64'], ['Maximum steps', '200']])
        m, b = r['test']['selected'], r['test']['random']
        sensitivity = []
        for alpha in ('0.1','0.5','0.9'):
            milestones = []
            for seed in r['seeds']:
                c = np.loadtxt(output/f'alpha_{alpha}_seed_{seed}_validation.csv', delimiter=',', skiprows=1, ndmin=2)
                hits = c[c[:,2] == 1.0, 0]
                milestones.append(str(int(hits[0])) if len(hits) else 'not reached')
            sensitivity.append(f'alpha={alpha}: first observed 100% validation success at episodes '+', '.join(milestones)+' (seeds 0/1/2).')
        page(pdf, 'Discussion, limitations and conclusion', [
            ('8. Baseline and selected agent',
             f'The selected alpha={r["selection"]["alpha"]}, seed-0 model obtained mean return {m["mean_return"]:.3f}, success {100*m["success_rate"]:.1f}%, mean length {m["mean_steps"]:.2f}, and {m["mean_illegal"]:.3f} illegal actions per episode on 500 test resets. The uniform-random baseline obtained return {b["mean_return"]:.3f}, success {100*b["success_rate"]:.1f}%, and mean length {b["mean_steps"]:.2f}.\n'
             f'The saved GIF records successful delivery in {r["demo"]["steps"]} steps with return {r["demo"]["total_return"]}. It illustrates one rollout; the larger test set measures reliability.'),
            ('9. Convergence and sensitivity', '\n'.join(sensitivity) + '\nThese checkpoint milestones measure observed learning speed, not a proof of convergence. A nonzero exploration floor leaves occasional penalties in training even after the greedy policy becomes reliable. The final test score alone can conceal differences in early sample efficiency.'),
            ('10. Failure modes and limitations',
             'Early exploration incurs illegal pickup/dropoff penalties and wall collisions. Unlearned or tied states can cause greedy loops until the time limit. Constant learning rates and a finite budget do not establish theoretical convergence. Three seeds give limited uncertainty estimates, and 500 sampled resets are not exhaustive verification. Only alpha was varied; discount and exploration sensitivity remain future work. This small deterministic benchmark does not demonstrate generalization to traffic, continuous control, or changing maps.'),
            ('11. Conclusion',
             'From-scratch tabular Q-learning learns a delivery policy on Taxi-v3. Separate validation and test rollouts, a random baseline, multiple training seeds, raw logs, and a rendered demonstration make the empirical findings auditable.'),
            ('References',
             'Farama Foundation: gymnasium.farama.org/environments/toy_text/taxi/\nFarama Foundation: gymnasium.farama.org/tutorials/gymnasium_basics/handling_time_limits/\nSutton & Barto (2018), Reinforcement Learning: An Introduction, 2nd ed., Chapter 6.\nEnvironment specification verified against the installed Gymnasium 1.2.1 source; current online documentation may describe newer versions.')])


if __name__ == '__main__':
    build_report()
